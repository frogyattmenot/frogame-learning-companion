// Copies the real Frogame Java files into app/data/finalAndroidCode.ts so the
// learning companion always shows the code you actually wrote.
// Runs automatically before `npm run dev` and `npm run build` (see package.json).
// If the Android project is not next to this folder, the existing data file is kept.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = path.dirname(fileURLToPath(import.meta.url));
const companionRoot = path.resolve(here, "..");
const javaRoot = path.resolve(companionRoot, "../app/src/main/java/edu/byuh/mc/cis/cs300/frogameproject");
const outFile = path.join(companionRoot, "app/data/finalAndroidCode.ts");

// Reading order for a beginner: screen → game rules → AI → drawing helpers → animation.
const purposes = {
  "ui/MainActivity.java": "The Android screen that starts the app and shows SecondView.",
  "ui/SecondView.java": "The game screen: draws the board, cards and tokens, handles taps, and runs the computer's turn.",
  "logic/GameMode.java": "Names the two ways to play: against the computer or against a friend.",
  "logic/Player.java": "Names the three possible values in a board square: X, O, or BLANK.",
  "logic/GameBoard.java": "The source of truth for the grid, turns, pushes, power cards, and winning.",
  "logic/PowerCard.java": "The four power cards (SKIP, REVERSE, +2, +4) and what each one does.",
  "logic/ComputerPlayer.java": "The computer opponent: looks several moves ahead with minimax and alpha-beta pruning.",
  "ui/GridButton.java": "One of the ten edge buttons (1–5 and A–E) that the player taps.",
  "Tokenzz.java": "One fruit token: built with a Builder, slides to its cell, and falls off the board when pushed out.",
  "ui/AnimationHandler.java": "Sends a tick about 60 times a second to every registered listener.",
  "ui/TickListener.java": "A one-method interface for anything that wants to hear each animation tick.",
};

if (!fs.existsSync(javaRoot)) {
  console.warn(`[sync-android-code] Android sources not found at ${javaRoot}; keeping existing data file.`);
  process.exit(0);
}

const found = [];
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name.endsWith(".java")) found.push(path.relative(javaRoot, full).split(path.sep).join("/"));
  }
})(javaRoot);

const ordered = [...Object.keys(purposes).filter((p) => found.includes(p)), ...found.filter((p) => !(p in purposes)).sort()];
// iCloud "Optimize Mac Storage" can leave a file on disk with no content (a "dataless"
// placeholder). Node then reads it as empty. Reading it with cat makes macOS download it.
// Files are only ever read here, never changed.
function readJava(file) {
  let text = fs.readFileSync(file, "utf8");
  if (text.length === 0 && fs.statSync(file).size > 0) text = execFileSync("cat", [file], { encoding: "utf8" });
  return text;
}

const files = ordered.map((p) => ({
  path: p,
  purpose: purposes[p] ?? "A Java file from the Frogame Android project.",
  code: readJava(path.join(javaRoot, p)).replace(/\r\n/g, "\n").replace(/\s+$/, ""),
}));

const empty = files.filter((f) => f.code.length === 0).map((f) => f.path);
if (empty.length) {
  console.warn(`[sync-android-code] Could not read ${empty.join(", ")} (still in iCloud?). Keeping existing data file.`);
  process.exit(0);
}

const body = `// AUTO-GENERATED by scripts/sync-android-code.mjs from the real Android project.
// Do not edit by hand: change the Java files, then run \`npm run sync-code\`.
export type FinalFile = { path: string; purpose: string; code: string };

export const finalAndroidFiles: FinalFile[] = ${JSON.stringify(files, null, 2)};
`;

if (!fs.existsSync(outFile) || fs.readFileSync(outFile, "utf8") !== body) fs.writeFileSync(outFile, body);
const missing = ordered.filter((p) => !(p in purposes));
console.log(`[sync-android-code] ${files.length} Java files synced.${missing.length ? ` New files without a purpose line: ${missing.join(", ")}` : ""}`);
